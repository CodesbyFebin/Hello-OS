import { describe, expect, test } from "bun:test"
import { cleanTurnPreview, derivePreview } from "../src/preview"

describe("cleanTurnPreview", () => {
  test("passes a plain human message through untouched", () => {
    expect(cleanTurnPreview("Help me fix the failing test")).toBe("Help me fix the failing test")
  })

  test("collapses internal whitespace/newlines", () => {
    expect(cleanTurnPreview("line one\n  line two")).toBe("line one line two")
  })

  test("returns the slash-command name for a command-wrapped turn", () => {
    const raw =
      "<command-message>plan-eng-review</command-message>\n" +
      "<command-name>/plan-eng-review</command-name>\n" +
      "<command-args>foo bar</command-args>"
    expect(cleanTurnPreview(raw)).toBe("/plan-eng-review")
  })

  test("falls back to command-message when there is no command-name", () => {
    expect(cleanTurnPreview("<command-message>office-hours</command-message>  ")).toBe("office-hours")
  })

  test("drops a turn that is only a Conductor system_instruction block", () => {
    expect(cleanTurnPreview("<system_instruction>\nYou are working inside Conductor\n</system_instruction>")).toBe("")
  })

  test("keeps real text that follows a stripped system_instruction block", () => {
    const raw = "<system_instruction>You are working inside Conductor</system_instruction>\n\nport my codex sessions"
    expect(cleanTurnPreview(raw)).toBe("port my codex sessions")
  })

  test("drops a system-reminder-only turn", () => {
    expect(cleanTurnPreview("<system-reminder>be nice</system-reminder>")).toBe("")
  })

  test("drops a codex AGENTS.md instructions turn", () => {
    expect(cleanTurnPreview("# AGENTS.md instructions <INSTRUCTIONS>- rule one</INSTRUCTIONS>")).toBe("")
  })

  test("empty / whitespace-only in -> empty out", () => {
    expect(cleanTurnPreview("")).toBe("")
    expect(cleanTurnPreview("   \n  ")).toBe("")
  })

  test("strips stray xml-ish tags but keeps the inner prose", () => {
    expect(cleanTurnPreview("<foo>hello</foo> world")).toBe("hello world")
  })

  test("drops a slash-command stdout echo turn", () => {
    expect(cleanTurnPreview("<local-command-stdout>Enabled plan mode</local-command-stdout>")).toBe("")
  })

  test("drops a local-command caveat banner turn", () => {
    expect(cleanTurnPreview("<local-command-caveat>Caveat: generated by local commands</local-command-caveat>")).toBe("")
  })

  test("strips ANSI escape codes", () => {
    expect(cleanTurnPreview("Set model to \x1b[1mFable 5\x1b[22m")).toBe("Set model to Fable 5")
  })

  test("drops an interrupt marker turn", () => {
    expect(cleanTurnPreview("[Request interrupted by user for tool use]")).toBe("")
  })
})

describe("derivePreview", () => {
  test("returns the first meaningful turn, skipping boilerplate", () => {
    const texts = [
      "<system_instruction>You are working inside Conductor</system_instruction>",
      "actually fix the bug in parser.ts",
    ]
    expect(derivePreview(texts)).toBe("actually fix the bug in parser.ts")
  })

  test("truncates to the max length", () => {
    expect(derivePreview(["abcdefghij"], 4)).toBe("abcd")
  })

  test("returns empty string when every turn is boilerplate", () => {
    expect(derivePreview(["<system-reminder>x</system-reminder>", "# AGENTS.md instructions"])).toBe("")
  })

  test("uses a slash-command turn as the title", () => {
    expect(derivePreview(["<command-name>/debug</command-name>"])).toBe("/debug")
  })

  test("appends the next turn when the first is a short bare command", () => {
    expect(derivePreview(["<command-name>plan</command-name>", "lets add more rows to the sample ui"])).toBe(
      "plan • lets add more rows to the sample ui",
    )
  })

  test("does not append when the first turn is already informative", () => {
    expect(
      derivePreview(["please refactor the parser to be tolerant of junk", "and add tests"]),
    ).toBe("please refactor the parser to be tolerant of junk")
  })

  test("keeps appending short turns until the preview is informative", () => {
    expect(derivePreview(["/plan", "yes", "make it fast"])).toBe("/plan • yes • make it fast")
  })

  test("a short first turn with no following turn stands alone", () => {
    expect(derivePreview(["/plan"])).toBe("/plan")
  })
})
