// Scans src/app for real page and route-handler files and writes
// src/lib/docs/route-manifest.ts. /llms.txt and the agent card read it, so
// discovery documents only list routes that exist. `--check` fails if stale.
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, relative, sep } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const app = join(root, "src/app");
const out = join(root, "src/lib/docs/route-manifest.ts");

function walk(dir, acc = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) walk(p, acc);
    else if (/^(page|route)\.tsx?$/.test(e.name)) acc.push(p);
  }
  return acc;
}

export function buildManifest() {
  const pages = [], api = [];
  for (const f of walk(app)) {
    const segs = relative(app, f).split(sep).slice(0, -1).filter((s) => !/^\(.*\)$/.test(s));
    const path = "/" + segs.join("/");
    if (f.endsWith("route.ts") || f.endsWith("route.tsx")) {
      const src = readFileSync(f, "utf8");
      const methods = ["GET", "POST", "PUT", "PATCH", "DELETE"].filter((m) => new RegExp(`export\\s+(async\\s+)?(function|const)\\s+${m}\\b`).test(src));
      api.push({ path, methods });
    } else pages.push({ path });
  }
  const by = (a, b) => a.path.localeCompare(b.path);
  return { pages: pages.sort(by), api: api.sort(by) };
}

const json = "// Generated by scripts/gen-route-manifest.mjs. Do not edit by hand.\nexport const ROUTE_MANIFEST = " + JSON.stringify(buildManifest(), null, 2) + " as const;\n";
if (process.argv.includes("--check")) {
  const cur = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (cur !== json) { console.error("route-manifest.ts is stale; run: node scripts/gen-route-manifest.mjs"); process.exit(1); }
  console.log("route manifest up to date");
} else { writeFileSync(out, json); console.log("wrote", relative(root, out)); }
